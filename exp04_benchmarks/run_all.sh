#!/usr/bin/env bash
# exp04: does fresh-text drift (Δbpb vs the family base) predict general-benchmark forgetting but not
# target-task gain?
#
# 18 checkpoints (cilab/stages.py STAGES: exp03's 14 plus exp01's SmolLM2 and Qwen3 pairs), benchmarked with
# lm-evaluation-harness on AAU, one array task per checkpoint (run_eval.py). General side: arc_easy,
# arc_challenge, hellaswag (2,000), piqa, winogrande, mmlu (40 per subject). Target side: gsm8k 5-shot (300),
# ifeval (200). Identical prompts for every model: no chat template. Predictors: exp03 stage_deltas.csv and
# exp01 bpb.csv. Correlations, CIs and the figure run on the Mac (analyze_forgetting.py).
#
# Pre-registered rules: RESULTS.md, section "Pre-registered rules", committed before the jobs ran.
#
# Steps (AAU, after the commit is pushed; from the Mac):
#   ssh -o BatchMode=yes aau 'cd ~/projects/compression-intelligence && infra/cluster/submit.sh exp04_setup'
#   ssh -o BatchMode=yes aau 'cd ~/projects/compression-intelligence && infra/cluster/submit.sh exp04_eval --array=4'
#       dry run on Qwen/Qwen2.5-0.5B (index 4): check summary.json parses, read the group timings
#   ssh -o BatchMode=yes aau 'cd ~/projects/compression-intelligence && infra/cluster/submit.sh exp04_eval --array=0-17%4'
#   chat-condition addendum (gsm8k + ifeval with each post-trained model's chat template; indices from
#   cilab.stages.post_trained_indices()):
#   ssh -o BatchMode=yes aau 'cd ~/projects/compression-intelligence && JOB_ARGS="--groups gsm8k_chat,ifeval_chat" infra/cluster/submit.sh exp04_eval --array=1,2,3,5,6,8,9,10,11,13,15,17%4 --time=01:00:00'
#   (Mac) bash run_all.sh fetch RUN=<~/runs/ci/exp04_eval/<run> on the cluster> SETUP=<exp04_setup run>
#   bash run_all.sh analyze     Mac: results/{scores.csv, correlations.csv, fig_forgetting.png, summary.md}
set -euo pipefail
cd "$(dirname "$0")/.."
PY=.venv/bin/python
OUT=exp04_benchmarks
mkdir -p $OUT/logs $OUT/results
case "${1:-analyze}" in
  fetch)
    : "${RUN:?RUN=<cluster run dir of exp04_eval>}"
    # lm-eval results JSON + done.json + summary.json per model (the samples index file is regenerated by run_eval.py)
    rsync -az --include='*/' --include='summary.json' --include='summary_chat.json' --include='done.json' --include='results.json' --include='results_*.json' \
          --exclude='*' "aau:$RUN/results/" $OUT/results/lm_eval/
    rsync -az --include='slurm-*.out' --include='commit.txt' --exclude='*' "aau:$RUN/" "$OUT/logs/${LOGS:-eval}/"
    if [ -n "${SETUP:-}" ]; then
      rsync -az --include='slurm-*.out' --include='commit.txt' --include='pip_freeze.txt' --exclude='*' \
            "aau:$SETUP/" $OUT/logs/setup/
    fi ;;
  analyze)
    $PY $OUT/analyze_forgetting.py > $OUT/logs/analyze.log 2>&1
    echo "done: $OUT/results/{scores.csv,correlations.csv,fig_forgetting.png,summary.md}" ;;
  *) echo "usage: run_all.sh [fetch|analyze]"; exit 1 ;;
esac
